#!/usr/bin/env python3
"""SombreMatter — the sleep phase.

Three deterministic operations, stdlib only:

  consolidate.py <hippocampus-log.md>    distill a session log into proposal notes
  consolidate.py --prune [--age-days N]  propose decay for never-hit notes
  consolidate.py --index                 refresh the maps in INDEX.md

Proposals land under sleep/<date>/proposals/. The cortex is never written
live: merging reviewed proposals IS the sleep event. Every memory write is
therefore a diff a human (or another agent) can reject.
"""

import argparse
import re
import sys
from datetime import date, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

FIELD_RES = {
    key: re.compile(rf"^{key}:\s*(.*)$", re.M)
    for key in ("id", "type", "title", "confidence", "source", "created",
                "last_hit", "hits", "status")
}


def frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---", text, re.S)
    out = {}
    if m:
        for key, rx in FIELD_RES.items():
            hit = rx.search(m.group(1))
            if hit:
                out[key] = hit.group(1).strip().strip('"')
    return out


def slugify(text):
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s[:60] or "note"


def parse_log(text):
    """Extract LEARN / EVIDENCE / TYPE blocks from a session log body."""
    body = re.sub(r"^---\n.*?\n---\n", "", text, count=1, flags=re.S)
    entries, cur = [], None
    for line in body.splitlines():
        line = line.strip()
        if line.startswith("LEARN:"):
            cur = {"claim": line[6:].strip(), "evidence": "", "kind": "semantic"}
            entries.append(cur)
        elif cur is not None and line.startswith("EVIDENCE:"):
            cur["evidence"] = line[9:].strip()
        elif cur is not None and line.startswith("TYPE:"):
            kind = line[5:].strip().lower()
            cur["kind"] = kind if kind in ("semantic", "procedural") else "semantic"
    return entries


def load_notes():
    """Map slug/id -> {path, region, fm, text} for cortex, striatum, amygdala."""
    notes = {}
    for region in ("cortex", "striatum", "amygdala"):
        for f in sorted((ROOT / region).glob("*.md")):
            text = f.read_text()
            entry = {"path": f, "region": region, "fm": frontmatter(text), "text": text}
            notes[f.stem] = entry
            fid = entry["fm"].get("id", "")
            if fid and fid not in notes:
                notes[fid] = entry
    return notes


def render_note(learning, slug, logname, confidence):
    region = "striatum" if learning["kind"] == "procedural" else "cortex"
    today = date.today().isoformat()
    return f"""---
id: {region}.{slug}
type: {learning['kind']}
title: {learning['claim']}
confidence: {confidence}
source: hippocampus/{logname}
created: {today}
last_hit: never
hits: 0
status: active
---

# {learning['claim']}

**Evidence** (hippocampus/{logname}): {learning['evidence'] or 'none recorded — treat as rumor.'}

<!-- Generated by sleep/consolidate.py on {today}. Review before merge. -->
"""


def cmd_consolidate(logpath):
    logname = logpath.name
    entries = parse_log(logpath.read_text())
    if not entries:
        print(f"consolidate: no LEARN blocks in {logname} — nothing to distill")
        return
    notes = load_notes()
    today = date.today().isoformat()
    pdir = ROOT / "sleep" / today / "proposals"
    pdir.mkdir(parents=True, exist_ok=True)

    rows, added, updated = [], 0, 0
    for e in entries:
        slug = slugify(e["claim"])
        target = "striatum" if e["kind"] == "procedural" else "cortex"
        existing = notes.get(slug)
        if existing and existing["region"] == target:
            fm = existing["fm"]
            try:
                old = float(fm.get("confidence", "0.3"))
            except ValueError:
                old = 0.3
            new = min(0.99, round(old + 0.1, 2))
            (pdir / f"{slug}.update.md").write_text(f"""# Reinforcement proposal — {fm.get('id', slug)}

Re-encountered in `hippocampus/{logname}`:

- `confidence`: {old} → **{new}**
- append to body: **Evidence** (hippocampus/{logname}): {e['evidence'] or 'none recorded.'}
- set `last_hit: {today}` and bump `hits`

Apply by hand to `{existing['path'].relative_to(ROOT)}` — this file is the diff.
""")
            updated += 1
            rows.append(("update", fm.get("id", slug), e["claim"], f"{old} → {new}"))
        else:
            (pdir / f"{slug}.md").write_text(render_note(e, slug, logname, "0.3"))
            added += 1
            rows.append(("create", f"{target}.{slug}", e["claim"], "0.3"))

    table = "\n".join(f"| {a} | `{i}` | {t} | {c} |" for a, i, t, c in rows)
    (pdir.parent / "PROPOSAL.md").write_text(f"""# Sleep proposal — {today}

**Log:** `hippocampus/{logname}` · **Learnings:** {len(entries)} ({added} new, {updated} reinforced)

| Action | Target | Title | Confidence |
|---|---|---|---|
{table}

## How to merge (this is the sleep event)

1. Copy each `proposals/<slug>.md` into `cortex/` — or `striatum/` when its id starts with `striatum.`.
2. Apply each `*.update.md` reinforcement diff by hand.
3. Review every note: no `source`, no merge. Contradicts an existing note? Create it with `supersedes:` and mark the old one `contradicted`.
4. Run `python3 sleep/consolidate.py --index` to refresh the maps in `INDEX.md`.
5. Commit as `sleep({today}): consolidated {logname}`.
""")
    print(f"consolidate: {len(entries)} learnings -> {added} new, "
          f"{updated} reinforced -> sleep/{today}/PROPOSAL.md")


def cmd_prune(age_days):
    today = date.today()
    pdir = ROOT / "sleep" / today.isoformat()
    pdir.mkdir(parents=True, exist_ok=True)

    rows, seen = [], set()
    for region in ("cortex", "striatum"):
        for f in sorted((ROOT / region).glob("*.md")):
            if f in seen:
                continue
            seen.add(f)
            fm = frontmatter(f.read_text())
            if fm.get("status", "active") != "active":
                continue
            if fm.get("hits", "0") != "0" or fm.get("last_hit", "never") != "never":
                continue
            try:
                created = datetime.strptime(fm.get("created", ""), "%Y-%m-%d").date()
            except ValueError:
                continue
            age = (today - created).days
            if age >= age_days:
                rows.append((fm.get("id", f.stem), fm.get("title", "(untitled)"), age))

    if rows:
        table = "\n".join(f"| `{i}` | {t} | {a}d |" for i, t, a in rows)
        (pdir / "PRUNE.md").write_text(f"""# Decay proposals — {today}

Notes never used since creation ({age_days}+ days). Set `status: decayed` —
the file stays, it just leaves the INDEX maps. Forgetting, not deleting.

| Note | Title | Age |
|---|---|---|
{table}
""")
    print(f"prune: {len(rows)} decay candidates (hits=0, age > {age_days}d) "
          f"-> sleep/{today}/PRUNE.md")


def cmd_index():
    counts = {}
    index = ROOT / "INDEX.md"
    text = index.read_text()
    for region, marker in (("cortex", "CORTEX-MAP"), ("striatum", "STRIATUM-MAP")):
        items = []
        for f in sorted((ROOT / region).glob("*.md")):
            fm = frontmatter(f.read_text())
            if fm.get("status", "active") in ("archived", "decayed"):
                continue
            fid = fm.get("id", f"{region}.{f.stem}")
            title = fm.get("title", fid)
            try:
                conf = float(fm.get("confidence", "0"))
            except ValueError:
                conf = 0.0
            items.append((conf, f"- `[[{fid}]]` {title} — conf {conf:g}, "
                          f"{fm.get('hits', '0')} hit(s)"))
        items.sort(reverse=True)
        counts[region] = len(items)
        body = "\n".join(line for _, line in items) or \
            "- *(empty — the first sleep will fill this)*"
        text = re.sub(rf"(<!-- {marker}:BEGIN -->\n).*?(<!-- {marker}:END -->)",
                      rf"\g<1>{body}\n\g<2>", text, flags=re.S)
    index.write_text(text)
    print(f"index: INDEX.md refreshed (cortex {counts['cortex']}, "
          f"striatum {counts['striatum']})")


def main():
    ap = argparse.ArgumentParser(description="SombreMatter sleep phase")
    ap.add_argument("log", nargs="?", help="hippocampus log file to consolidate")
    ap.add_argument("--prune", action="store_true")
    ap.add_argument("--index", action="store_true")
    ap.add_argument("--age-days", type=int, default=30)
    args = ap.parse_args()

    if args.index:
        cmd_index()
    elif args.prune:
        cmd_prune(args.age_days)
    elif args.log:
        logpath = Path(args.log)
        if not logpath.exists():
            sys.exit(f"consolidate: log not found: {logpath}")
        cmd_consolidate(logpath)
    else:
        ap.print_help()


if __name__ == "__main__":
    main()
